#!/bin/bash

# Exit immediately if a command exits with a non-zero status
set -e

# Get version from argument, default to 1.0.0 if not provided
VERSION=${1:-1.0.0}

echo "Starting build process for version $VERSION..."

# 1. Build the bundles from source.
# The legacy target is gone: nothing ever enqueued *-legacy.js, and unlike the
# modern target -- which externalises React to window.React -- it compiled React,
# ReactDOM, scheduler and moment into the output. package.sh still deletes any
# *-legacy.js it finds while staging, since wp-scripts builds with clean:false
# and stale files from an older checkout would otherwise be copied into the zip.
echo "Running npm run build..."
npm run build

# 4. Add headers
# All four shipped bundles get one -- the two block bundles previously shipped
# minified with no header at all.
FILES=("build/admin.js" "build/settings.js" "build/block-checkout.js" "build/block-cart.js")

# lucide-react is compiled into the two admin bundles only. Its ISC licence
# requires the notice be retained in distributions, and the modern build emits
# no *.LICENSE.txt (the minifier strips lucide's own @license banner), so the
# notice has to be carried here. No URL -- just the retained notice.
declare -A BUNDLED_ISC=(
    ["build/admin.js"]=1
    ["build/settings.js"]=1
)

# Loop through each file and prepend the header
for file in "${FILES[@]}"; do
    if [ -f "$file" ]; then
        echo "Adding header to $file..."

        # Built outside the heredoc: a failing `[ -n ]` inside a command
        # substitution propagates its exit status to the assignment, which
        # `set -e` would treat as a fatal error for the non-lucide bundles.
        ISC_NOTICE=""
        if [ -n "${BUNDLED_ISC[$file]}" ]; then
            ISC_NOTICE="
 *
 * Bundled: lucide-react (ISC)."
        fi

        HEADER="/*
 * PointBay
 * Copyright (c) $(date +%Y) WPAnchorBay - https://wpanchorbay.com
 *
 * This software is licensed under the GPLv2 or later.
 * This file is generated from un-compiled source code. Do not edit this file directly.
 *
 * Source Code (Root): https://github.com/wpanchorbay/pointbay-free/tree/$VERSION/
 * Uncompressed source: https://github.com/wpanchorbay/pointbay-free/tree/$VERSION/src$ISC_NOTICE
 */"

        echo "$HEADER" | cat - "$file" > "${file}.tmp" && mv "${file}.tmp" "$file"
        echo "Successfully added header to $file"
    else
        echo "Warning: File $file not found."
    fi
done

# 5. Add headers to the compiled stylesheets.
# The WordPress.org guideline on human-readable code covers CSS as well as JS,
# and build/*.css is minified Tailwind output, so each one has to point at its
# own source the same way the bundles do. Globbed rather than listed because
# wp-scripts also emits an -rtl.css for every stylesheet; naming them by hand
# meant the RTL variants shipped bare. This runs AFTER `npm run build`, so the
# headers land on freshly emitted files and are never applied twice.
for file in build/*.css; do
    [ -f "$file" ] || continue

    echo "Adding header to $file..."

    CSS_HEADER="/*
 * PointBay
 * Copyright (c) $(date +%Y) WPAnchorBay - https://wpanchorbay.com
 *
 * This software is licensed under the GPLv2 or later.
 * This file is generated from un-compiled source code. Do not edit this file directly.
 * It is compiled from src/styles/index.scss (Sass + Tailwind CSS via PostCSS).
 *
 * Source Code (Root): https://github.com/wpanchorbay/pointbay-free/tree/$VERSION/
 * Uncompressed source: https://github.com/wpanchorbay/pointbay-free/tree/$VERSION/src/styles
 */"

    echo "$CSS_HEADER" | cat - "$file" > "${file}.tmp" && mv "${file}.tmp" "$file"
    echo "Successfully added header to $file"
done

echo "Build and header addition complete for version $VERSION."
