#!/bin/bash
#
# rename.sh — Rebrand LoyaltyBay -> PointBay across the free and pro repos.
#
# Referenced by package.json's "rebranding" script. Drives the ~150 token edits
# of the WordPress.org-mandated rename as one reproducible, reviewable diff.
#
# Usage (from either plugin root):
#   bash rename.sh                    # dry run: report what would change
#   bash rename.sh --apply            # rewrite files in place
#   bash rename.sh --apply <dir>...   # explicit repo roots
#
# Defaults to operating on BOTH sibling repos, because pro references free by
# fully-qualified class name in ~20 places and a free-only rename leaves pro fatal.
#
# What this script does NOT do (deliberately — each needs a human):
#   * composer dump-autoload -o        (regenerates vendor/, which is excluded here)
#   * npm run build                    (regenerates build/, which is excluded here)
#   * npm run makepot                  (regenerates languages/*.pot, deleted here)
#   * mv of the plugin DIRECTORIES     (they are repo roots — outside git)
#   * renaming the public GitHub repo  (wpanchorbay/loyaltybay-free -> pointbay-free)
#
set -euo pipefail

APPLY=0
ROOTS=()

for arg in "$@"; do
    case "$arg" in
        --apply) APPLY=1 ;;
        --dry-run) APPLY=0 ;;
        -*) echo "Unknown flag: $arg" >&2; exit 1 ;;
        *) ROOTS+=("$arg") ;;
    esac
done

# Default to both sibling repos, resolved relative to this script.
if [ ${#ROOTS[@]} -eq 0 ]; then
    HERE="$(cd "$(dirname "$0")" && pwd)"
    PARENT="$(dirname "$HERE")"
    ROOTS=(
        "$PARENT/loyaltybay-loyalty-points-referral-rewards-woo"
        "$PARENT/loyaltybaypro"
    )
fi

# ---------------------------------------------------------------------------
# Substitutions, LONGEST TOKEN FIRST.
#
# Order is load-bearing. The full slug must be rewritten before the bare
# `loyaltybay` token, and every *Pro variant before its non-Pro counterpart —
# otherwise `loyaltybaypro` becomes `pointbaypro` only by accident and
# `LOYALTYBAY_PRO_REMOTE_URL` corrupts into `POINTBAY_PRO_...` mid-token.
#
# `Loyaltybay` (lowercase b) appears only in readme.txt's title, where the
# casing was already wrong; it collapses into the correct `PointBay`.
# ---------------------------------------------------------------------------
SUBS=(
    'loyaltybay-loyalty-points-referral-rewards-woo|pointbay-loyalty-points-referral-rewards-woo'
    'loyaltybay-free|pointbay-free'
    'LOYALTYBAY_PRO|POINTBAY_PRO'
    'LoyaltyBayPro|PointBayPro'
    'loyaltybaypro|pointbaypro'
    'loyaltybay_pro|pointbay_pro'
    'LOYALTYBAY|POINTBAY'
    'LoyaltyBay|PointBay'
    'Loyaltybay|PointBay'
    'loyaltybay|pointbay'
)

# Paths never rewritten: third-party or generated. vendor/ is regenerated by
# composer dump-autoload, build/ by npm run build, *.pot by makepot.
EXCLUDE_RE='^(node_modules/|vendor/|build/|dist/|graphify-out/|test-results/|rename.sh$|languages/.*\.pot$|package-lock\.json$)'

total_files=0
total_hits=0

for ROOT in "${ROOTS[@]}"; do
    if [ ! -d "$ROOT/.git" ]; then
        echo "!! Skipping $ROOT — not a git repo" >&2
        continue
    fi

    echo
    echo "=============================================================="
    echo "  $ROOT"
    echo "=============================================================="

    cd "$ROOT"

    # git ls-files gives us tracked files only, so untracked build junk and
    # anything gitignored is out of scope by construction. -I skips binaries.
    mapfile -t FILES < <(
        git ls-files -z \
        | tr '\0' '\n' \
        | grep -Ev "$EXCLUDE_RE" \
        | while IFS= read -r f; do
            [ -f "$f" ] || continue
            grep -Iqs 'loyaltybay\|LoyaltyBay\|LOYALTYBAY\|Loyaltybay' "$f" && echo "$f"
          done
    )

    if [ ${#FILES[@]} -eq 0 ]; then
        echo "  (nothing to do)"
        continue
    fi

    for f in "${FILES[@]}"; do
        hits=$(grep -Ioc 'loyaltybay\|LoyaltyBay\|LOYALTYBAY\|Loyaltybay' "$f" || true)
        total_hits=$(( total_hits + hits ))
        total_files=$(( total_files + 1 ))
        printf '  %5s  %s\n' "$hits" "$f"

        if [ "$APPLY" = "1" ]; then
            for pair in "${SUBS[@]}"; do
                from="${pair%%|*}"
                to="${pair##*|}"
                sed -i "s/${from}/${to}/g" "$f"
            done
        fi
    done

    if [ "$APPLY" = "1" ]; then
        # Rename the main plugin file. git mv keeps history attached.
        if [ -f "loyaltybay-loyalty-points-referral-rewards-woo.php" ]; then
            git mv "loyaltybay-loyalty-points-referral-rewards-woo.php" \
                   "pointbay-loyalty-points-referral-rewards-woo.php"
            echo "  -> renamed main plugin file"
        fi
        if [ -f "loyaltybaypro.php" ]; then
            git mv "loyaltybaypro.php" "pointbaypro.php"
            echo "  -> renamed main plugin file"
        fi

        # Drop the stale POT — it carries the old domain, the old filename and
        # line references that the rename invalidates. Regenerate with makepot.
        if compgen -G "languages/*.pot" > /dev/null; then
            rm -f languages/*.pot
            echo "  -> removed stale languages/*.pot (run 'npm run makepot')"
        fi
    fi
done

echo
echo "--------------------------------------------------------------"
printf '  %d files, %d occurrences\n' "$total_files" "$total_hits"
if [ "$APPLY" = "1" ]; then
    cat <<'NEXT'

  Applied. Now, in order:

    1. composer dump-autoload -o     (in BOTH repos — vendor/ is tracked)
    2. npm run build                 (in BOTH repos — silent failure if skipped:
                                      the admin screen renders an empty loader)
    3. npm run makepot               (free only)
    4. Verify the atomic groups A-N by hand; sed cannot catch a hardcoded
       getElementById('loyaltybay') that has already been rewritten correctly
       but whose bundle was never rebuilt.
    5. mv the two plugin DIRECTORIES, then fix pro's qit.json (it references
       free by both old slug and old relative path).
    6. Deactivate/reactivate free: the capability rename otherwise leaves
       admins without manage_pointbay and every REST endpoint 403s, and the
       rewrite flush is what keeps /my-rewards from 404ing.
    7. Drop the orphaned wp_loyaltybay_* tables — there is no upgrade routine,
       so reactivation creates fresh empty ones and the old data lingers.
NEXT
else
    echo
    echo "  Dry run. Re-run with --apply to rewrite."
fi
